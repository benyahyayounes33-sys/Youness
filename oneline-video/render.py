def place(layer_img, cx, cy, s, rot, canvas, mode, fill):
    """Paste a transformed kiss layer into canvas (PIL). mode: 'mult'|'add'|'L'."""
    w, h = layer_img.size
    im = layer_img.resize((max(1, int(w * s)), max(1, int(h * s))), Image.BICUBIC)
    im = im.rotate(rot, resample=Image.BICUBIC, expand=True, fillcolor=fill)
    x, y = int(cx - im.width / 2), int(cy - im.height / 2)
    if mode == "mult":
        lay = Image.new("RGB", canvas.size, (255, 255, 255))
        lay.paste(im, (x, y))
        return ImageChops.multiply(canvas, lay)
    lay = Image.new(canvas.mode, canvas.size, 0 if canvas.mode == "L" else (0, 0, 0))
    lay.paste(im, (x, y))
    return ImageChops.add(canvas, lay) if mode == "add" else ImageChops.lighter(canvas, lay)


