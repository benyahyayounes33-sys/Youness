def montage_or_transition(t, fi):
    k = max(0, min(7, sum(1 for c in CUTS[1:8] if t >= c)))
    for j in range(7):  # transition between scene j and j+1 at CUTS[j+1]
        c = CUTS[j + 1]
        hw = HW[TRANS[j]] / FPS
        if c - hw <= t < c + hw:
            p = (t - (c - hw)) / (2 * hw)
            A, B = montage_frame(j, t), montage_frame(j + 1, t)
            kind = TRANS[j]
            if kind == "whip_h":
                return tr_whip(A, B, p, 1)
            if kind == "whip_v":
                return tr_whip(A, B, p, 0)
            if kind == "zoom_punch":
                return tr_zoom(A, B, p)
            if kind == "light_leak":
                return tr_leak(A, B, p)
            if kind == "spin":
                return tr_spin(A, B, p)
            if kind == "glitch":
                return tr_glitch(A, B, p, fi)
            if kind == "wipe":
                return tr_wipe(A, B, p)
    return montage_frame(k, t)


