def kiss_asset(box):
    c = np.asarray(LIPS_SRC.crop(box)).astype(np.float32)
    h, w, _ = c.shape
    border = np.concatenate([c[:6].reshape(-1, 3), c[-6:].reshape(-1, 3), c[:, :6].reshape(-1, 3), c[:, -6:].reshape(-1, 3)])
    bg = np.percentile(border, 80, axis=0)
    ink = np.clip((bg[1] - 15 - c[..., 1]) / (bg[1] - 75), 0, 1)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    e = ((xx - w / 2) / (w * 0.5)) ** 2 + ((yy - h / 2) / (h * 0.5)) ** 2
    F = np.clip((1 - e) / 0.22, 0, 1)
    T = np.clip(c / bg, 0, 1)
    win = (np.abs(xx - w / 2) < w * 0.25) & (np.abs(yy - h / 2) < h * 0.22) & (ink < 0.25)
    ys, xs = np.nonzero(win)
    gx, gy = xs.mean(), ys.mean()
    ev, evec = np.linalg.eigh(np.cov(np.stack([xs - gx, ys - gy])))
    ang = math.atan2(evec[1, 1], evec[0, 1])
    rmaj, rmin = 2.0 * math.sqrt(ev[1]), 2.0 * math.sqrt(ev[0])
    dx, dy = xx - gx, yy - gy
    u = dx * math.cos(ang) + dy * math.sin(ang)
    v = -dx * math.sin(ang) + dy * math.cos(ang)
    gap = (1 - ink) * np.clip((1.7 - ((u / rmaj) ** 2 + (v / rmin) ** 2)) / 0.9, 0, 1)
    ink_f = ink * F
    mult = 1 - F[..., None] * (1 - T)                                  # multiply layer (paper)
    prem = c / 255 * ink_f[..., None]                                    # premultiplied (black bg)
    return {"mult": Image.fromarray((mult * 255).astype(np.uint8)),
            "prem": Image.fromarray((np.clip(prem, 0, 1) * 255).astype(np.uint8)),
            "gap": Image.fromarray((np.clip(gap, 0, 1) * 255).astype(np.uint8), "L"),
            "g": (gx - w / 2, gy - h / 2), "size": (w, h)}


