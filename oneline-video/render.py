def _up(x, k):
    n = x.shape[1]
    X = np.fft.rfft(x, axis=1)
    Y = np.zeros((x.shape[0], n * k // 2 + 1), complex)
    Y[:, :X.shape[1]] = X
    return np.fft.irfft(Y, n * k, axis=1) * k


def _down(y, k, n):
    Y = np.fft.rfft(y, axis=1)[:, :n // 2 + 1]
    f = np.fft.rfftfreq(n, 1 / SR)
    Y *= 1 / np.sqrt(1 + (f / 18000) ** 8)
    return np.fft.irfft(Y, n, axis=1) / k


def true_peak_limit(x, tp_db):
    """Soft-clip at 4x oversampling (no aliasing / inter-sample overs), then set true peak."""
    n = x.shape[1]
    y = _down(np.tanh(_up(x, 4)), 4, n)
    tp = np.abs(_up(y, 4)).max()
    return y * (10 ** (tp_db / 20) / tp)


def master_eq(x):
    """Phone-friendly master: low cut, softer sub, a little air."""
    def g(f):
        sm = lambda a, b: np.clip((f - a) / (b - a), 0, 1) ** 2 * (3 - 2 * np.clip((f - a) / (b - a), 0, 1))
        hp2 = (f / 28) ** 2 / np.sqrt(1 + (f / 28) ** 4)
        return hp2 * (0.5 + 0.5 * sm(45, 140)) * (1 + 0.4 * sm(2500, 7000))
    return np.stack([fft_filter(x[c], g) for c in range(2)])


def write_wav(path, st):
    st = np.clip(st, -1, 1).T
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((st * 32767).astype("<i2").tobytes())


