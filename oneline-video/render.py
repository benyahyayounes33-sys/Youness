def tr_whip(A, B, p, axis):
    e = ease_io(p)
    de = (ease_io(min(1, p + 0.02)) - ease_io(max(0, p - 0.02))) / 0.04
    n = W if axis == 1 else H
    canvas = np.concatenate([A, B], axis=axis)
    off = int(e * n)
    L = int(de * n / 7)
    lo, hi = max(0, off - L), min(2 * n, off + n + L)
    reg = np.take(canvas, np.arange(lo, hi), axis=axis)
    reg = box_blur(reg, L, axis)
    return np.take(reg, np.arange(off - lo, off - lo + n), axis=axis)


def radial(a, s, amount):
    acc = np.zeros_like(a)
    for i in range(4):
        acc += zscale(a, s * (1 + amount * i))
    return acc / 4


def rgb_split(a, d):
    d = int(d)
    if d == 0:
        return a
    out = a.copy()
    out[..., 0] = np.roll(a[..., 0], d, 1)
    out[..., 2] = np.roll(a[..., 2], -d, 1)
    return out


def tr_zoom(A, B, p):
    if p < 0.5:
        q = p * 2
        out = radial(A, 1 + 0.7 * ease_in(q), 0.03 * q)
        return rgb_split(out, 16 * q) * (1 + 0.45 * ease_in(q))
    q = p * 2 - 1
    out = radial(B, 1 + 0.3 * (1 - ease_out(q)), 0.03 * (1 - q))
    return rgb_split(out, 16 * (1 - q)) * (1 + 0.45 * (1 - q))


def tr_leak(A, B, p):
    m = ease_io(seg(p, 0.35, 0.65))
    base = A * (1 - m) + B * m
    env = math.sin(math.pi * p) ** 1.2 * 0.9
    lk = leak(p) * env
    return 1 - (1 - np.clip(base, 0, 1)) * (1 - np.clip(lk, 0, 1))


def tr_spin(A, B, p):
    if p < 0.5:
        q = p * 2
        ang, s, X, sp = 100 * ease_in(q), 1 + 1.0 * ease_in(q), A, q
    else:
        q = p * 2 - 1
        ang, s, X, sp = -100 * (1 - ease_out(q)), 1 + 1.0 * (1 - ease_out(q)), B, 1 - q
    im = to_pil(X)
    bl = 7 * sp
    acc = sum(from_pil(im.rotate(ang + d, resample=Image.BILINEAR)) for d in (-bl, 0, bl)) / 3
    return zscale(acc, s)


def tr_glitch(A, B, p, fi):
    r = np.random.default_rng(1000 + fi)
    src = A if (p < 0.5) != (r.random() < 0.3) else B
    out = src.copy()
    it = math.sin(math.pi * p)
    y = 0
    while y < H:
        hh = int(r.integers(20, 180))
        if r.random() < 0.55:
            out[y:y + hh] = np.roll(src[y:y + hh], int(r.uniform(-110, 110) * it), axis=1)
        y += hh
    out = rgb_split(out, 18 * it)
    out[::3] *= 1 - 0.18 * it
    return out


def tr_wipe(A, B, p):
    e = lerp(-0.12, 1.12, ease_io(p))
    m = np.clip((e - DIAG) / 0.04 + 0.5, 0, 1)
    glow = np.exp(-((DIAG - e) / 0.02) ** 2) * 0.9
    return A * (1 - m) + B * m + glow * np.array([1.0, 0.92, 0.86], np.float32)


